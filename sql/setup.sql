--  KMBNO — Generator Umów Przedwstępnych
--  Tabela na dane pełnomocników, które wcześniej leżały w kodzie.
--  Wykonaj RAZ w Supabase → SQL Editor → New query → Run.
--
--  Tabela `ustawienia` (token Monday, mocodawca, podpis) powstała już
--  przy generatorze umów z wykonawcami — to ten sam projekt Supabase,
--  więc tutaj nie trzeba jej zakładać ponownie.
-- ══════════════════════════════════════════════════════════════════

create table if not exists public.pelnomocnicy (
  id            bigint generated by default as identity primary key,
  imie_nazwisko text not null,
  adres         text,
  dowod         text,
  pesel         text,
  utworzono     timestamptz not null default now()
);

alter table public.pelnomocnicy enable row level security;

create policy "peln_select" on public.pelnomocnicy
  for select to authenticated using (true);
create policy "peln_insert" on public.pelnomocnicy
  for insert to authenticated with check (true);
create policy "peln_update" on public.pelnomocnicy
  for update to authenticated using (true) with check (true);
create policy "peln_delete" on public.pelnomocnicy
  for delete to authenticated using (true);
